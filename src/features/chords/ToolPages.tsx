/** /chords/checker — the method's checks on any shape you type. */
export function CheckerPage() {
  const [sym, setSym] = useState('Cmaj7')
  const [shape, setShape] = useState('x-8-x-9-9')
  const F = useFingers()
  const r = useMemo(() => {
    try {
      return analyse(sym, shape)
    } catch (e) {
      return (e as Error).message
    }
  }, [sym, shape])
  return (
    <Page
      label="Tool"
      title="Shape checker"
      lead="Type a chord and frets, low string to high (B‑E‑A‑D‑G). The checker works out every note and degree from the frets and tests the shape the way every shape in this method was tested: each note must belong to the chord, the hand must reach it (measured in millimetres at that place on the neck: about four frets in the middle, five and more above the 12th fret), and neighbours below their clear floor are flagged ([[Law2]]). What it cannot test is how the shape feels in your hand and sounds through your rig: those two tests are yours."
    >
      <Section>
        <FieldGrid>
          <Field label="Chord symbol">
            <input className={s.input} value={sym} onChange={(e) => setSym(e.target.value)} />
          </Field>
          <Field label="Frets (x muted, 0 open, h7 harmonic, a9 artificial harmonic)">
            <input className={s.input} value={shape} onChange={(e) => setShape(e.target.value)} />
          </Field>
        </FieldGrid>
      </Section>
      <Section>
        {typeof r === 'string' ? (
          <p className={s.errors}>{r}</p>
        ) : (
          <div className={s.result}>
            {r.errors.length ? (
              <ul className={s.errors}>
                {r.errors.map((e) => (
                  <li key={e}>{e}</li>
                ))}
              </ul>
            ) : (
              <span className={s.ok}>✓ Every note belongs to {sym}, and the hand can reach it{r.stretch ? ' (a stretch)' : ''}.</span>
            )}
            {r.errors.length === 0 && (
              <div className={s.cards}>
                <ShapeCard I={info(sym, shape)} />
              </div>
            )}
            {r.warnings.length > 0 && (
              <ul className={s.warnings}>
                {r.warnings.map((w) => (
                  <li key={w}>{w}</li>
                ))}
              </ul>
            )}
            {r.errors.length === 0 && <FingeringList sym={sym} shape={shape} hand={F.hand} />}
            <div className={s.tableWrap}>
            <table className={s.table}>
              <thead>
                <tr>
                  <th>String</th>
                  <th>Fret</th>
                  <th>Pitch</th>
                  <th>Note</th>
                  <th>Degree</th>
                  <th>Register</th>
                </tr>
              </thead>
              <tbody>
                {r.notes.map((n) => (
                  <tr key={n.str}>
                    <td>{STRING_NAMES[n.str]}</td>
                    <td>{n.harmonic ? `harmonic over ${n.fret}` : n.artificial ? `${n.fret}, touched at ${n.fret + 12}` : n.fret}</td>
                    <td>{pitchName(n.midi)}</td>
                    <td>{n.name}</td>
                    <td>{n.deg}</td>
                    <td>{bandsOf(n.midi).join(' / ') || 'above the bands'}</td>
                  </tr>
                ))}
              </tbody>
            </table>
            </div>
          </div>
        )}
      </Section>
    </Page>
  )
}

/** The fingerings the hand model finds for a shape, best first, with how hard each one is. */
function FingeringList({ sym, shape, hand }: { sym: string; shape: string; hand: 'average' | 'large' }) {
  const I = info(sym, shape)
  const notes = I.a.notes.map((n) => ({ str: n.str, fret: n.fret }))
  const all = fingerings(notes, hand).slice(0, 4)
  const effort = (c: number) => (c < 0.7 ? 'easy' : c < 1.6 ? 'comfortable' : c < 3 ? 'takes practice' : 'a real stretch')
  return (
    <div>
      <p className={s.caption}>
        <CText text={`**Fingering** for ${hand === 'large' ? 'a large' : 'an average'} hand (change it in ⚙ Settings). The hand is measured in millimetres on a 34″ neck, so the same span is easier high up than near the nut ([[Ch10]]).`} />
      </p>
      {all.length === 0 ? (
        <p className={s.errors}>No fingering fits this hand: the reach is too wide. Play the root first and the rest after (Law 5: time is your second hand), or move the shape up the neck.</p>
      ) : (
        <ol className={s.steps}>
          {all.map((f, i) => (
            <li key={i}>
              <CText text={fingerText(I, { f, fingers: f.fingers, barres: f.barres, hand: handOf(notes.map((n) => n.fret), f) })} /> · index at fret {f.pos} · <b>{effort(f.cost)}</b>
              {i === 0 ? ' (shown above)' : ''}
            </li>
          ))}
        </ol>
      )}
    </div>
  )
}
