/** /chords/generator — any progression, any key, any layer, voiced by the laws. */
export function GeneratorPage() {
  const [pid, setPid] = useState('two-five')
  const [key, setKey] = useState('C')
  const [layer, setLayer] = useState<Layer>('shell')
  const [dom, setDom] = useState<DomColour>('auto')
  const [around, setAround] = useState(9)
  const [custom, setCustom] = useState('Dm7 G7 | Cmaj7 A7 | Dm7 G7 | Cmaj7')
  const F = useFingers()
  const p = progById(pid)
  const bars = useMemo(() => {
    if (pid !== 'custom') return progIn(p!, key)
    return custom
      .split('|')
      .map((b) => b.trim().split(/\s+/).filter(Boolean))
      .filter((b) => b.length)
  }, [pid, key, custom, p])
  const parsed = useMemo(() => {
    try {
      bars.flat().forEach(parseSym)
      return voiced(bars, layer, dom, around, F.hand)
    } catch (e) {
      return (e as Error).message
    }
  }, [bars, layer, dom, around, F.hand])
  return (
    <Page
      label="Tool"
      title="Progression generator"
      lead="Pick a progression, a key and a layer. Every chord gets the clearest shape ([[Law2]]) that keeps the hand and the voices moving as little as possible ([[Law4]]); dominants take their colours from where they go ([[R5]]). Predict the shapes first, then check."
    >
      <Section>
        <FieldGrid>
          <Field label="Progression">
            <Select value={pid} options={[...PROGS.map((x) => ({ value: x.id, label: x.name })), { value: 'custom', label: 'Your own…' }]} onChange={setPid} />
          </Field>
          {pid !== 'custom' && (
            <Field label="Key">
              <Select value={key} options={KEYS.map((k) => ({ value: k, label: k + (p?.minor ? ' minor' : '') }))} onChange={setKey} />
            </Field>
          )}
          <Field label="Layer">
            <Select value={layer} options={layerOpts} onChange={(v) => setLayer(v as Layer)} />
          </Field>
          <Field label="Dominant colours">
            <Segmented label="Dominant colours" value={dom} options={[{ value: 'auto', label: 'by destination' }, { value: 'plain', label: '9 13' }, { value: 'altered', label: '♯9 ♭13' }]} onChange={setDom} />
          </Field>
          <Field label={`Hand around fret ${around}`}>
            <Slider min={3} max={16} value={around} onChange={setAround} />
          </Field>
        </FieldGrid>
        <p className={s.caption}>
          <CText text={reachWords(around, F.hand)} />
        </p>
        {pid === 'custom' && (
          <Field label="Chords (bars split by |, e.g. Dm7 G7 | Cmaj7)">
            <input className={s.input} value={custom} onChange={(e) => setCustom(e.target.value)} />
          </Field>
        )}
      </Section>
      <Section>
        {typeof parsed === 'string' ? (
          <p className={s.errors}>{parsed}</p>
        ) : (
          <Voiced key={parsed.text} V={parsed.V} barsText={parsed.text} title={pid === 'custom' ? 'Your progression' : `${p!.name} in ${key}`} pattern={pid.includes('blues') ? 'four' : 'split'} />
        )}
      </Section>
    </Page>
  )
}

