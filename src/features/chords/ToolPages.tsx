/** /chords/test-progressions — Appendix B, re-voiced with every layer. */
export function TestsPage() {
  const [layer, setLayer] = useState<'base' | Layer>('base')
  const F = useFingers()
  return (
    <Page
      label="The spiral"
      title="The four test progressions"
      lead="The same four progressions come back at the end of every part ([[Ch10]], [[Ch15]], [[Ch19]]), each time with the new layer. The tune stays the same and the chords get richer, so you hear your own progress. Record yourself at every checkpoint and keep the recordings."
    >
      <Section>
        <FieldGrid>
          <Field label="Layer">
            <Select value={layer} options={[{ value: 'base', label: 'Baseline shells (the method’s shapes)' }, ...layerOpts]} onChange={(v) => setLayer(v as 'base' | Layer)} />
          </Field>
        </FieldGrid>
        {layer !== 'base' && (
          <p className={s.caption}>
            <CText text={`${LAYERS.find((l) => l.value === layer)!.what}. Generated by the laws: each shape as clear as possible ([[Law2]]), each move as small as possible ([[Law4]]).`} />
          </p>
        )}
      </Section>
      {TESTS.map((t) => {
        const bars = t.bars.split('|').map((b) => b.trim().split(/\s+/).map((x) => x.slice(0, x.indexOf(':'))))
        const g = layer === 'base' ? null : voiced(bars, layer, 'auto', 9, F.hand)
        const V = g ? g.V : t.bars.split('|').flatMap((b) => b.trim().split(/\s+/)).map((x) => ({ sym: x.slice(0, x.indexOf(':')), shape: x.slice(x.indexOf(':') + 1) }))
        return (
          <Section key={t.id + layer}>
            <SectionTitle>{t.name}</SectionTitle>
            <p className={s.caption}>{t.note}</p>
            <Voiced V={V} barsText={g ? g.text : t.bars} title={t.name} pattern={t.id === 't4' ? 'four' : 'split'} />
          </Section>
        )
      })}
    </Page>
  )
}

