/** The keys an exercise goes through, in order. */
export const ROUTES = {
  near: { keys: ['C', 'F', 'B♭', 'E♭'], say: 'four keys, each a fourth above the last' },
  sharp: { keys: ['G', 'D', 'A', 'E'], say: 'the four sharp keys, each a fifth above the last' },
  low: { keys: ['E', 'F', 'F♯', 'G'], say: 'the four lowest keys on the neck' },
  blues: { keys: ['F', 'B♭', 'E♭', 'C', 'G'], say: 'the five usual blues keys' },
  thirds: { keys: ['C', 'A♭', 'E'], say: 'three starting notes a major 3rd apart: together they reach all twelve roots' },
  half: { keys: ['C', 'D♭', 'D', 'E♭'], say: 'four keys a half step apart: together they reach all twelve key centres' },
  cycle: { keys: ['C', 'F', 'B♭', 'E♭', 'A♭', 'D♭', 'F♯', 'B', 'E', 'A', 'D', 'G'], say: 'all twelve keys, each a fourth above the last' },
  mixed: { keys: ['C', 'E♭', 'F♯', 'A', 'D', 'F', 'A♭', 'B', 'E', 'G', 'B♭', 'D♭'], say: 'all twelve keys in an order with no pattern to lean on' },
} as const
export type RouteId = keyof typeof ROUTES

export type ExKind = 'shape' | 'cadence' | 'texture' | 'predict' | 'place' | 'piece' | 'review'
export const KIND_NAME: Record<ExKind, string> = {
  shape: 'Shape study',
  cadence: 'Cadence',
  texture: 'Texture',
  predict: 'Work it out first',
  place: 'Place on the neck',
  piece: 'Piece',
  review: 'Checkpoint',
}

export interface Exercise {
  /** A name that never changes (progress is saved under it). The number comes from the order. */
  id: string
  unit: number
  kind: ExKind
  title: string
  /** The chapters of the method it practises (ids): read them first. */
  ch: string[]
  /** What the hand and the ear learn (rich text). */
  aim: string
  /** How to practise it (rich text). */
  steps: string[]
  /** The test for moving on. */
  pass: string
  /** A progression: an id of progressions.ts or of OWN below. */
  prog: string
  layer: Layer
  style?: Style
  /** The fret the hand works around: 5 low, 9 middle, 14 high. */
  around?: number
  dom?: DomColour
  pattern?: PatternId
  /** Tempo to start at, and the goal. */
  tempo: [number, number]
  /** 'one' = only the key the progression is written in. */
  keys: RouteId | 'one'
  /** The shapes stay hidden until you ask: work them out first. */
  blind?: boolean
  /** Let the player move the exercise between the low, middle and high part of the neck. */
  places?: boolean
  /** Upper notes as artificial harmonics. */
  bells?: boolean
  /** Only shapes made of these degrees (an exercise about one interval). */
  only?: string[]
}

