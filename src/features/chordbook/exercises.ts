/**
 * The exercise book of the chord method: numbered exercises, from two notes on one chord to long forms in twelve keys.
 *
 * An exercise does not store shapes. It names a progression, a voicing (a layer of the method), a place on the neck and
 * a set of keys; the voicing engine works the shapes out for the key chosen and for the hand set in Settings. So each
 * exercise is an assignment: what to play, how, in which keys, how fast, and the test for moving on.
 *
 * Difficulty rises by one thing at a time: a new voicing, more keys, a harder order of keys, a new texture, a higher
 * tempo, or the shapes hidden until you have worked them out.
 */
